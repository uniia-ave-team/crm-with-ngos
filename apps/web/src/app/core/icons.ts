/** Назва іконки застосунку. */
export type IconName = keyof typeof ICONS;

/** Набір іконок: Lucide (Safari) чи Material Symbols (інші браузери). */
export type IconSet = 'lucide' | 'material';

/**
 * Safari (на Mac, iPhone, iPad) — за `User-Agent`: є `Safari/`, але нема позначок інших браузерів
 * (Chrome, Edge, Firefox, Opera, Samsung на iOS чи деінде теж пишуть `Safari/`).
 */
export function isSafari(userAgent: string): boolean {
  return /Safari\//.test(userAgent) && !/(Chrome|Chromium|CriOS|FxiOS|EdgiOS|Edg|OPR|OPiOS|SamsungBrowser|YaBrowser|Android)/.test(userAgent);
}

/** Набір для цього браузера. */
export function iconSetFor(userAgent: string): IconSet {
  return isSafari(userAgent) ? 'lucide' : 'material';
}

/**
 * SVG для `ion-icon` (data-URL). Текст SVG — як є, без кодування: адресу з `;utf8,` Ionicons
 * розбирає `DOMParser`-ом просто з рядка (так працює й зі строгою CSP). Material Symbols без
 * заливки в самому файлі — додаємо `fill="currentColor"`, щоб іконка брала колір тексту (Lucide вже
 * малює `stroke="currentColor"`), і примітку про цю зміну на початку (`MATERIAL_FILL_NOTICE`,
 * Apache 2.0, п. 4b).
 */
export function iconSvg(name: IconName, set: IconSet): string {
  const svg = set === 'material' ? `${MATERIAL_FILL_NOTICE}\n${ICONS[name].material.replace('<svg ', '<svg fill="currentColor" ')}` : ICONS[name].lucide;
  return `data:image/svg+xml;utf8,${svg}`;
}

/** Реєструє всі іконки набору цього браузера (раз, на старті застосунку). */
export function registerIcons(userAgent: string = typeof navigator === 'undefined' ? '' : navigator.userAgent): IconSet {
  const set = iconSetFor(userAgent);
  addIcons(Object.fromEntries((Object.keys(ICONS) as IconName[]).map((name) => [name, iconSvg(name, set)])));
  return set;
}

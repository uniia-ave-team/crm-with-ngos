export const DERIVED_ICON_NOTICE = '<!-- Changed by the Yavir web client: the plus is replaced with a minus. -->';
/** Примітка про зміну, яку отримує кожна іконка Material Symbols (до неї додано `fill`). */
export const MATERIAL_FILL_NOTICE = '<!-- Changed by the Yavir web client: fill="currentColor" is added to the svg element. -->';

/**
 * Змінена копія іконки: замінює частину SVG (`from` → `to`), додає перед `<svg>` примітку про зміну
 * (`DERIVED_ICON_NOTICE`; коментар `@license` Lucide лишається) і падає, якщо частини нема
 * (оновлення пакета змінило файл — заміна мовчки не спрацювала б). Так зроблено «видалити рядок» і
 * «видалити стовпчик»: в обох наборах є лише «додати», тож у копії плюс стає мінусом. Ліцензії це
 * дозволяють (ISC: «use, copy, modify»; Apache 2.0, п. 2 і 4); зміни описано в `licenses/README.md`.
 */
function derive(svg: string, from: string, to: string): string {
  if (!svg.includes(from)) {
    throw new Error(`[icons] Іконку не змінено: нема «${from}»`);
  }
  return svg.replace(from, to).replace('<svg', `${DERIVED_ICON_NOTICE}\n<svg`);
}


/**
 * Звʼязок рукописних запитів із контрактом API. Типи моделей генеруються з
 * `packages/api-contract/openapi.json` у `api/generated` (npm-хуки перед запуском, збіркою,
 * тестами й лінтом) і використовуються лише як типи: запити сервіси шлють самі.
 *
 * - Тіло запиту позначається `satisfies <Модель>`: якщо контракт зміниться (поле перейменують,
 *   додадуть обовʼязкове), збірка впаде, а не піде на сервер неправильний запит.
 * - Відповідь читається як `Untrusted<Модель>`: назви полів звіряються з контрактом (звернення
 *   до поля, якого в контракті нема, — помилка збірки), але значенням під час виконання не
 *   довіряємо. Сервер іншої версії чи збій можуть віддати що завгодно, тож кожне поле має тип
 *   `unknown` і перевіряється перед використанням.
 */
export type Untrusted<T> = { readonly [Key in keyof T]?: unknown } | null | undefined;
